package com.example.data.models

/**
 * Data model for an athlete registered in the Ethiopian Combat Athlete Registry.
 */
data class RegisteredAthlete(
    val athleteId: String,
    val fullName: String,
    val amharicName: String = "",
    val nickname: String = "",
    val gender: String = "Male",
    val dob: String = "1998-01-01",
    val region: String = "Addis Ababa",
    val phoneNumber: String = "",
    val nationalId: String = "",
    val primarySport: String = "Mixed Martial Arts (MMA)",
    val competitionLevel: String = "Semi-Pro / Showcase",
    val weightClass: String = "Middleweight (84 kg)",
    val stance: String = "Orthodox",
    val clubAffiliation: String = "",
    val coachName: String = "",
    val coachPhone: String = "",
    val proWins: Int = 0,
    val proLosses: Int = 0,
    val proDraws: Int = 0,
    val proFinishes: Int = 0,
    val amateurRecord: String = "0-0-0",
    val heightCm: Int = 180,
    val reachCm: Int = 180,
    val notableTitles: String = "",
    val beltRank: String = "",
    val licenseNo: String = "",
    val lastOpponent: String = "",
    val lastEvent: String = "",
    val lastResult: String = "",
    val footageUrl: String = "",
    val medicalStatus: String = "Fit & Medically Cleared",
    val profilePhotoUri: String? = null,
    val status: String = "Vetting In Progress",
    val leagueAssignment: String = "Pending ETFC Review",
    val registrationTimestamp: Long = System.currentTimeMillis()
) {
    /**
     * Converts this registry entry into a standard Fighter entity for use throughout the ETFC Stream app.
     */
    fun toFighter(): Fighter {
        val divisionEnum = when {
            weightClass.contains("Light Heavy", ignoreCase = true) -> WeightClass.LIGHT_HEAVYWEIGHT
            weightClass.contains("Heavyweight", ignoreCase = true) -> WeightClass.HEAVYWEIGHT
            weightClass.contains("Middleweight", ignoreCase = true) -> WeightClass.MIDDLEWEIGHT
            weightClass.contains("Welterweight", ignoreCase = true) -> WeightClass.WELTERWEIGHT
            weightClass.contains("Lightweight", ignoreCase = true) -> WeightClass.LIGHTWEIGHT
            weightClass.contains("Featherweight", ignoreCase = true) -> WeightClass.FEATHERWEIGHT
            weightClass.contains("Bantamweight", ignoreCase = true) -> WeightClass.BANTAMWEIGHT
            weightClass.contains("Flyweight", ignoreCase = true) -> WeightClass.FLYWEIGHT
            else -> WeightClass.MIDDLEWEIGHT
        }

        val disciplineEnum = when {
            primarySport.contains("Boxing", ignoreCase = true) -> MatchCategory.BOXING
            primarySport.contains("Muay Thai", ignoreCase = true) -> MatchCategory.MUAY_THAI
            else -> MatchCategory.MMA
        }

        return Fighter(
            id = "f_reg_${athleteId.lowercase().replace("-", "_")}",
            name = fullName,
            nickname = nickname.ifBlank { "The Contender" },
            countryName = "Ethiopia",
            flagEmoji = "🇪🇹",
            division = divisionEnum,
            wins = proWins,
            losses = proLosses,
            draws = proDraws,
            kos = proFinishes,
            submissions = 0,
            strikeAccuracyPercent = 65,
            takedownDefensePercent = 75,
            reachInches = (reachCm / 2.54).toInt().coerceIn(60, 90),
            heightCm = heightCm,
            stance = stance,
            isChampion = false,
            rank = 5,
            bio = "${if (amharicName.isNotBlank()) "$amharicName • " else ""}$clubAffiliation • $notableTitles",
            signatureMove = beltRank.ifBlank { "Cross Hammer" },
            primaryColorHex = 0xFFFAB818,
            discipline = disciplineEnum,
            photoUrl = profilePhotoUri
        )
    }

    fun toMap(): Map<String, Any?> {
        return hashMapOf(
            "athleteId" to athleteId,
            "fullName" to fullName,
            "amharicName" to amharicName,
            "nickname" to nickname,
            "gender" to gender,
            "dob" to dob,
            "region" to region,
            "phoneNumber" to phoneNumber,
            "nationalId" to nationalId,
            "primarySport" to primarySport,
            "competitionLevel" to competitionLevel,
            "weightClass" to weightClass,
            "stance" to stance,
            "clubAffiliation" to clubAffiliation,
            "coachName" to coachName,
            "coachPhone" to coachPhone,
            "proWins" to proWins,
            "proLosses" to proLosses,
            "proDraws" to proDraws,
            "proFinishes" to proFinishes,
            "amateurRecord" to amateurRecord,
            "heightCm" to heightCm,
            "reachCm" to reachCm,
            "notableTitles" to notableTitles,
            "beltRank" to beltRank,
            "licenseNo" to licenseNo,
            "lastOpponent" to lastOpponent,
            "lastEvent" to lastEvent,
            "lastResult" to lastResult,
            "footageUrl" to footageUrl,
            "medicalStatus" to medicalStatus,
            "profilePhotoUri" to (profilePhotoUri ?: ""),
            "status" to status,
            "leagueAssignment" to leagueAssignment,
            "registrationTimestamp" to registrationTimestamp
        )
    }

    companion object {
        fun fromMap(id: String, data: Map<String, Any?>): RegisteredAthlete {
            return RegisteredAthlete(
                athleteId = (data["athleteId"] as? String) ?: id,
                fullName = (data["fullName"] as? String) ?: "Unknown Athlete",
                amharicName = (data["amharicName"] as? String) ?: "",
                nickname = (data["nickname"] as? String) ?: "",
                gender = (data["gender"] as? String) ?: "Male",
                dob = (data["dob"] as? String) ?: "1998-01-01",
                region = (data["region"] as? String) ?: "Addis Ababa",
                phoneNumber = (data["phoneNumber"] as? String) ?: "",
                nationalId = (data["nationalId"] as? String) ?: "",
                primarySport = (data["primarySport"] as? String) ?: "Mixed Martial Arts (MMA)",
                competitionLevel = (data["competitionLevel"] as? String) ?: "Semi-Pro / Showcase",
                weightClass = (data["weightClass"] as? String) ?: "Middleweight (84 kg)",
                stance = (data["stance"] as? String) ?: "Orthodox",
                clubAffiliation = (data["clubAffiliation"] as? String) ?: "",
                coachName = (data["coachName"] as? String) ?: "",
                coachPhone = (data["coachPhone"] as? String) ?: "",
                proWins = ((data["proWins"] as? Number)?.toInt()) ?: 0,
                proLosses = ((data["proLosses"] as? Number)?.toInt()) ?: 0,
                proDraws = ((data["proDraws"] as? Number)?.toInt()) ?: 0,
                proFinishes = ((data["proFinishes"] as? Number)?.toInt()) ?: 0,
                amateurRecord = (data["amateurRecord"] as? String) ?: "0-0-0",
                heightCm = ((data["heightCm"] as? Number)?.toInt()) ?: 180,
                reachCm = ((data["reachCm"] as? Number)?.toInt()) ?: 180,
                notableTitles = (data["notableTitles"] as? String) ?: "",
                beltRank = (data["beltRank"] as? String) ?: "",
                licenseNo = (data["licenseNo"] as? String) ?: "",
                lastOpponent = (data["lastOpponent"] as? String) ?: "",
                lastEvent = (data["lastEvent"] as? String) ?: "",
                lastResult = (data["lastResult"] as? String) ?: "",
                footageUrl = (data["footageUrl"] as? String) ?: "",
                medicalStatus = (data["medicalStatus"] as? String) ?: "Fit & Medically Cleared",
                profilePhotoUri = (data["profilePhotoUri"] as? String)?.ifBlank { null },
                status = (data["status"] as? String) ?: "Vetting In Progress",
                leagueAssignment = (data["leagueAssignment"] as? String) ?: "Pending ETFC Review",
                registrationTimestamp = ((data["registrationTimestamp"] as? Number)?.toLong()) ?: System.currentTimeMillis()
            )
        }
    }
}

